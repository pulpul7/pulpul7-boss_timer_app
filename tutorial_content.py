def validate_content():
    """Validate actual-view routes before blocking any physical input."""
    from tutorial_live_ui import VIEWS, route
    keys = set()
    for chapter in CHAPTERS:
        if chapter.key in keys or not chapter.steps:
            raise ValueError(f"Invalid tutorial chapter: {chapter.key}")
        keys.add(chapter.key)
        for step in chapter.steps:
            view, target = route(step.view, step.target)
            if view not in VIEWS or not target:
                raise ValueError(f"Missing live target: {chapter.key}/{step.view}/{step.target}")
