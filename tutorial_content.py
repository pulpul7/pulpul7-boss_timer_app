    steps = []
    for key, body in MANAGEMENT:
        steps.append(s("main", key, key.lstrip("@"), body))
        view = MAIN_OPENERS.get(key)
        if view:
            steps.append(s(view, "@window", key + " 화면 확인", body + " 열린 실제 화면에서 위치를 확인하세요. 저장·적용·삭제는 튜토리얼에서 실행하지 않습니다."))
    return tuple(steps)


